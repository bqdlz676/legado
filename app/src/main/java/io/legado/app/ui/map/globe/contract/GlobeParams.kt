package io.legado.app.ui.map.globe.contract

import io.legado.app.ui.components.ComponentPalette

/**
 * S-19 3D 地球仪 · 契约层参数单源（平台无关层，纯数值，不引用任何 Android / Compose 类型，
 * 普通 JVM 单测可直接断言）。
 *
 * 〔锚点原文〕
 *  - `docs/落文-规格切片/切片-19-3D地球仪细节.md:7`：远距 LOD0 128×128 / 2K Blue Marble
 *  - `docs/落文-规格切片/切片-19-3D地球仪细节.md:40`：暗半球降到 0.15 亮度 + 偏蓝
 *  - `docs/落文-规格切片/切片-19-3D地球仪细节.md:41`：晨昏线不是硬切，一个 5° 宽渐变带
 *  - `docs/落文-规格切片/切片-19-3D地球仪细节.md:46`：星空固定不动，地球在里面自转
 *  - `docs/落文-规格切片/切片-19-3D地球仪细节.md:49`：地球模型按 23.5° 倾斜，光照计算基于倾斜后的球面法线
 *  - `docs/落文-规格切片/切片-19-3D地球仪细节.md:61`：手指离开后带惯性继续转 0.8s（速度衰减到 0）
 *  - `docs/落文-规格切片/切片-19-3D地球仪细节.md:66`：球面段数（远距）128×128
 *  - `docs/落文-规格切片/切片-18-3D地球仪战役回放.md:64`：金色光针 + 顶部金点
 *  - `docs/落文-规格切片/切片-20-3D沙盘与地球仪合并.md:66`：关隘脉冲金点
 *  - `docs/落文-规格切片/切片-20-3D沙盘与地球仪合并.md:94`：自动旋转 0.2°/s，指间惯性慢转 0.8s 停稳
 *  - `docs/落文-规格切片/切片-20-3D沙盘与地球仪合并.md:118`：SphereGeometry(100, 128, 128)
 *
 * 〔为什么集中一处〕
 * 倾角 / 衰减时长 / 网格密度 / 光照分界 / 标记点规格只在本对象登记；后续渲染层接线时只允许
 * 引用本表，不在画面里另写魔法数字，避免契约层、既有 GlobeConfig、单测三处口径漂移。
 *
 * 〔颜色口径〕
 * 本对象不持有任何色值，只转发 [ComponentPalette] 指定四色 token（BG_PAGE / BRAND_GOLD /
 * TEXT_TERTIARY / STONE_BLUE），不写裸 hex；地貌纹理色归既有 GlobeSpecSurface，不在此重复。
 *
 * 〔本单边界〕
 * 本单只做契约层（参数 + 纯函数 + 纯 JVM 单测），不写 GLES / Compose 渲染，不改既有
 * `ui/map/globe/` 实现；G1（23.5° 倾斜接光照）与 G8（128×128 bench）是历史返工项，
 * 其渲染接线与性能口径仍归既有渲染 / bench 文件，本单不重做。
 */
object GlobeParams {

    // ─────────────────────────── 地轴 ───────────────────────────

    /**
     * 地轴倾角 23.5°：切片-19:49「地球模型按 23.5° 倾斜——不是直上直下转，是斜着转…
     * 光照计算基于倾斜后的球面法线方向」。本常量只登记角度，不做旋转变换；倾斜接光照归渲染层。
     */
    const val AXIAL_TILT_DEG: Double = 23.5

    // ─────────────────────────── 自转 ───────────────────────────

    /**
     * 自转周期 ms。
     * // [已拍板 2026-11-25] 原推定值 0L；用户 2026-11-25 指令拍板：自动旋转 0.2°/s，
     * 转一圈 360 / 0.2 = 1800 秒 = 1,800,000ms，落码 1_800_000L；与自动旋转 0.2°/s
     * 同一口径。出处：用户 2026-11-25 拍板指令；此值不许再改。
     */
    const val ROTATION_PERIOD_MS: Long = 1_800_000L

    // ─────────────────────────── 惯性衰减 ───────────────────────────

    /**
     * 松手后惯性滑行时长 800ms：切片-19:61「手指离开后地球不立刻停——带惯性继续转 0.8s
     * （速度衰减到 0），跟真实地球仪的手感一样」；[spinDecay] 按此时长线性衰减到 0。
     */
    const val INERTIA_DECAY_MS: Long = 800L

    // ─────────────────────────── 经纬网格密度 ───────────────────────────

    /**
     * 经线条数（远距 LOD0）：切片-19:7「远距（整球可见）LOD0 128×128」、
     * 切片-19:66「球面段数（远距）128×128」。
     */
    const val GRID_MERIDIANS: Int = 128

    /** 纬线条数（远距 LOD0）：同切片-19:7 / :66，128×128，与经线成对登记。 */
    const val GRID_PARALLELS: Int = 128

    // ─────────────────────────── 球面半径 ───────────────────────────

    /**
     * 球面半径 dp。
     * // [已拍板 2026-11-25] 原推定值 0f；用户 2026-11-25 指令拍板：球面半径 100 单位，
     * `SphereGeometry(100, 128, 128)`，落码 100f，与既有 [GRID_MERIDIANS] / [GRID_PARALLELS]
     * = 128 成对。出处：用户 2026-11-25 拍板指令（切片-20:118）；此值不许再改。
     */
    const val RADIUS_DP: Float = 100f

    // ─────────────────────────── 标记点 ───────────────────────────

    /**
     * 标记点直径 dp。
     * // [已拍板 2026-11-25] 原推定值 0f；用户 2026-11-25 指令拍板：标记点 4dp，与城池标签
     * 同尺寸，落码 4f。出处：用户 2026-11-25 拍板指令；此值不许再改。
     */
    const val MARKER_DOT_DIAMETER_DP: Float = 4f

    /**
     * 标记点脉冲周期 ms。
     * // [已拍板 2026-11-25] 原推定值 0L；用户 2026-11-25 指令拍板：1200ms，与棋子呼吸光晕
     * 一致，落码 1200L。出处：用户 2026-11-25 拍板指令；此值不许再改。
     */
    const val MARKER_PULSE_PERIOD_MS: Long = 1200L

    // ─────────────────────────── 昼夜光照分界 ───────────────────────────

    /**
     * 晨昏线渐变带宽 5°：切片-19:41「晨昏线（日照和暗的交界）不是硬切——一个 5° 宽的渐变带」。
     */
    const val TERMINATOR_BAND_DEG: Double = 5.0

    /** 暗半球亮度系数 0.15：切片-19:40「暗半球 降到 0.15 亮度 + 偏蓝」。 */
    const val NIGHT_BRIGHTNESS: Float = 0.15f

    // ─────────────────────────── 颜色（只转发四色 token，不写裸 hex） ───────────────────────────

    /** 标记金点 / 光针色：取 [ComponentPalette.BRAND_GOLD]；切片-18:64 顶部金点。 */
    val markerGold: Long get() = ComponentPalette.BRAND_GOLD

    /** 经纬网格线色：取 [ComponentPalette.TEXT_TERTIARY]，辅助线灰褐，不抢地表细节。 */
    val gridLineTertiary: Long get() = ComponentPalette.TEXT_TERTIARY

    /** 暗半球偏蓝色：取 [ComponentPalette.STONE_BLUE]；切片-19:40 暗半球偏蓝。 */
    val nightSideStoneBlue: Long get() = ComponentPalette.STONE_BLUE

    /** 兜底背景色：取 [ComponentPalette.BG_PAGE]；星空背景属渲染层，契约层只留纸白兜底。 */
    val backdropBgPage: Long get() = ComponentPalette.BG_PAGE
}
