def build_core(legacy_core, ner_hits, ts):
    core = dict(legacy_core)
    next_id = 1
    for v in core.values():
        try:
            next_id = max(next_id, int(v["id"][1:]))
        except ValueError:
            pass
    extra_aliases = []
    for e in L1_EXTRA:
        (name, zi, hao, fief, birth, death, rs, re_, state,
         identity, deed, chapter, event_year, aliases) = e
        key = to_simp(name, ts)
        if key in {to_simp(v["name"], ts) for v in core.values()}:
            continue
        next_id += 1
        feat = deed
        if rs is not None:
            feat = f"{deed}（{rs}—{re_}）" if deed else f"在位{rs}—{re_}"
        ner_chapters = [c for c in (ner_hits.get(key) or ner_hits.get(name) or []) if c]
        if not chapter and ner_chapters:
            chapter = "、".join(ner_chapters[:3])
        core[name] = dict(
            id=f"p{next_id:04d}", name=name, dynasty="",
            birth=birth, death=death, identity=identity, feat=feat,
            state=state, source="L1 手校种子", confidence=CONF_HIGH,
            proofread="1", zi=zi, hao=hao, fief=fief,
            chapter=chapter, event_year=event_year if event_year is not None else "",
            reign_s=rs, reign_e=re_, aliases=aliases,
        )
        extra_aliases.extend((name, a, t, state) for a, t in aliases)
    return core, extra_aliases


