RANK_SUFFIX = "公侯伯子男王"


def build_aliases(legacy_alias, core, princes, extra_aliases):
    rows = {}

    def put(alias, owner, atype, state, start=None, end=None, sources=None):
        if not alias or not owner:
            return
        key = (alias, owner, atype, state)
        if key in rows:
            if sources:
                rows[key]["sources"].update(sources)
            return
        rows[key] = dict(alias=alias, owner=owner, atype=atype, state=state,
                         start=start, end=end, sources=set(sources or []))

    for r in legacy_alias:
        # 回填旧表只记基线来源；跨源命中由本次 core/王公 合并环节重新叠加，
        # 不读回旧 source 字符串，避免重跑时来源重复、置信度虚高。
        put(r["alias"], r["owner"], r["atype"], r["state"],
            r["start"], r["end"], {SRC_LEGACY})

    for c in core.values():
        if c["zi"]:
            put(c["zi"], c["name"], "字", c["state"], sources={SRC_CANON})
        if c["hao"]:
            for h in str(c["hao"]).split("、"):
                if h:
                    put(h, c["name"], "号", c["state"], sources={SRC_CANON})
        if c["fief"]:
            for f in str(c["fief"]).split("、"):
                if f:
                    put(f, c["name"], "封号", c["state"], sources={SRC_CANON})
        for a, _t in c.get("aliases", []):
            put(a, c["name"], _t, c["state"], sources={SRC_CANON})

    for name, alias, atype, state in extra_aliases:
        put(alias, name, atype, state, sources={SRC_CANON})

    # 王公谥称：鲁桓公 → 桓公（归属鲁桓公，国鲁，在位区间随世系）
    for pr in princes:
        title = pr["title"]
        if title and title[-1] in RANK_SUFFIX:
            put(title, pr["state"] + title, "谥称", pr["state"],
                pr["start"], pr["end"], sources=set(pr["sources"]))

    out = list(rows.values())
    for r in out:
        r["confidence"] = score_confidence(r["sources"])
        r["source"] = source_str(r["sources"])
    return out


