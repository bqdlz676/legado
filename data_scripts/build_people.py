def build_persons(cbdb, canon_keys, ner_hits, ts):
    """返回 (primary_rows, dup_rows, terms_extra)。

    主表按繁简归一键合并（与消费端 PersonProfile 同一归一键）；
    同名消歧分组按原始人名（与 PersonDup 消费端一致），≥2 条才入 dup 表。
    """
    simp_groups = {}
    for row in cbdb:
        key = to_simp(row["name"], ts)
        simp_groups.setdefault(key, []).append(row)

    primary, dup_rows, terms_extra = [], [], []
    for key, members in simp_groups.items():
        first = members[0]
        aliases = list(first["aliases"])
        for other in members[1:]:
            for a in other["aliases"]:
                if a not in aliases:
                    aliases.append(a)
        sources = {SRC_CBDB}
        if key in ner_hits:
            sources.add(SRC_NER)
        if key in canon_keys:
            sources.add(SRC_WD)  # 内嵌正史种子作为 Wikidata 交叉快照
        conf = score_confidence(sources)
        primary.append(dict(
            name=first["name"], aliases=aliases,
            birth=first["birth"], death=first["death"],
            dynasty=first["dynasty"], identity=first["identity"],
            source=source_str(sources), confidence=conf,
        ))
        terms_extra.append(first["name"])
        terms_extra.extend(aliases)

    # 同名消歧：按繁简归一键分组；组内朝代/生卒可区分才入 dup 表，
    # 至少一人有朝代或生卒；孤证沉底 L3。p[0] 写归一键，异体/繁体入别名列。
    for key, members in simp_groups.items():
        if len(members) < 2:
            continue
        meta = {(m["dynasty"], m["birth"], m["death"]) for m in members}
        has_meta = any(m["dynasty"] or m["birth"] is not None or m["death"] is not None
                       for m in members)
        if len(meta) < 2 or not has_meta:
            continue
        variants = sorted({m["name"] for m in members if m["name"] != key})
        for m in members:
            has_date = m["birth"] is not None or m["death"] is not None
            dup_conf = "L2" if has_date else "L3"
            alias = "、".join(m["aliases"] + [v for v in variants if v not in m["aliases"]])
            dup_rows.append(dict(
                name=key,
                birth=m["birth"] if m["birth"] is not None else "",
                death=m["death"] if m["death"] is not None else "",
                dynasty=m["dynasty"], identity=m["identity"],
                confidence=dup_conf, alias=alias,
                source=SRC_CBDB,
            ))
    return primary, dup_rows, terms_extra


