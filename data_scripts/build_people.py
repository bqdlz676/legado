def write_princes(rows):
    body = []
    for r in sorted(rows, key=lambda x: (x["state"], x["start"] if x["start"] is not None else 0)):
        start = r["start"]
        end = r["end"]
        if start is not None and end is not None and end >= start:
            span = end - start + 1
        elif start is not None:
            span = 1
        else:
            span = 0
        body.append([
            r["state"], r["title"],
            "" if start is None else start, span,
            "" if end is None else end,
            r["source"], r["confidence"],
        ])
    write_tsv(ASSETS / "princes.txt",
              ["国", "称号", "即位公元年", "在位年数", "末年在位公元年", "source", "confidence"], body)


def write_era(eras):
    clean = []
    seen = set()
    for e in eras:
        n, d = e.get("n", ""), e.get("d", "")
        a, b = norm_year(e.get("a")), norm_year(e.get("b"))
        if not n or a is None:
            continue
        if b is None:
            b = a
        if b < a:
            b = a
        key = (n, d, a, b)
        if key in seen:
            continue
        seen.add(key)
        clean.append({"n": n, "d": d, "a": a, "b": b})
    clean.sort(key=lambda x: (x["a"], x["n"]))
    (ASSETS / "era.json").write_text(
        json.dumps(clean, ensure_ascii=False, separators=(",", ":")), encoding="utf-8")


