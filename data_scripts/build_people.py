SKIP_STATES = {"五代", "未詳", "朝鮮", "高麗"}


def norm_state(s: str) -> str:
    s = (s or "").strip()
    return STATE_MAP.get(s, s)


def build_princes(legacy, cbdb, ts):
    table = {}

    def get(state, title):
        return table.setdefault((state, title), dict(
            state=state, title=title, start=None, end=None, sources=set()))

    # S1/S2：Wikidata + Wikipedia 离线快照（内嵌正史世系种子，两源互证）
    for state, lst in MONARCHS.items():
        for title, start, end in lst:
            row = get(state, title)
            row["start"] = start
            row["end"] = end
            row["sources"].update({SRC_WD, SRC_WP})

    # S3：既有正史世系表复核；回填时沿用其已记录来源标签，
    # 不无条件叠加 SRC_LEGACY，避免重跑造成来源膨胀、置信度虚高。
    for r in legacy:
        state = norm_state(r["state"])
        if state in SKIP_STATES:
            continue
        row = get(state, r["title"])
        if row["start"] is None:
            row["start"] = r["start"]
            row["end"] = r["end"]
        seeds = {s for s in r["old_src"].split("/") if s} or {SRC_LEGACY}
        row["sources"].update(seeds)

    # S4：CBDB 身份字段中的统治者/皇帝（孤证，low）
    for m in cbdb:
        if not NOBLE_RE.search(m["identity"] or ""):
            continue
        state = norm_state(m["dynasty"])
        if state in SKIP_STATES:
            continue
        row = get(state, to_simp(m["name"], ts))
        row["sources"].add(SRC_CBDB)
        if row["start"] is None:
            row["start"] = m["birth"]
            row["end"] = m["death"]

    out = []
    for row in table.values():
        # 无即位年的条目运行时会被 Chronology 跳过，不编年份，直接沉底不入表；
        # 其人仍保留在 person 主表，身份线索不丢失。
        if row["start"] is None:
            continue
        row["confidence"] = score_confidence(row["sources"])
        row["source"] = source_str(row["sources"])
        out.append(row)
    return out


