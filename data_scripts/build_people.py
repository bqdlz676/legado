def _read_lines(path: Path):
    if not path.exists():
        return []
    return [ln.rstrip("\n") for ln in path.read_text(encoding="utf-8").splitlines()]


def norm_year(v, default=None):
    if v is None:
        return default
    s = str(v).strip()
    if not s:
        return default
    try:
        return int(s)
    except ValueError:
        return default


def score_confidence(sources):
    """三来源命中数 → high / medium / low。"""
    n = len({s for s in sources if s})
    if n >= 3:
        return CONF_HIGH
    if n == 2:
        return CONF_MEDIUM
    return CONF_LOW


SRC_ORDER = [SRC_CBDB, SRC_WD, SRC_WP, SRC_NER, SRC_CANON, SRC_LEGACY]


def source_str(sources):
    """固定优先级排序，保证重跑幂等（避免集合迭代顺序受哈希随机化影响）。"""
    ss = {s for s in sources if s}
    ordered = [s for s in SRC_ORDER if s in ss] + sorted(ss - set(SRC_ORDER))
    return "/".join(ordered)


def load_ts_map():
    """繁→简归一键表（复用 assets/ts.txt，与消费端 PersonProfile 同一套）。"""
    m = {}
    for ln in _read_lines(ASSETS / "ts.txt"):
        if not ln or ln.startswith("#"):
            continue
        p = ln.split("\t")
        if len(p) >= 2 and len(p[0]) == 1:
            simp = p[1].split(" ")[0]
            if len(simp) == 1:
                m[p[0][0]] = simp[0]
    return m


def to_simp(s: str, ts: dict) -> str:
    if not ts:
        return s
    return "".join(ts.get(c, c) for c in s)


def is_cjk_term(s: str) -> bool:
    return 2 <= len(s) <= 5 and all("一" <= c <= "鿿" for c in s)


