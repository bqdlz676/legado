# 章名整行匹配：◇隐公元年 / 卷一 梁惠王上；注疏句含标点，不视为章名
CHAPTER_RE = re.compile(r"^◇?([^\s　（()，。：；、“”\"']{2,8})年$")
JUAN_RE = re.compile(r"^卷[一二三四五六七八九十\d]+\s*([^\s　（()，。：；、]{2,10})")
BAD_CHAPTER_CHARS = set("，。：；、（）()“”\"'？！")


def _clean_chapter(title: str) -> str:
    title = title.strip().strip("　")
    if not title or len(title) > 10:
        return ""
    if any(c in title for c in BAD_CHAPTER_CHARS):
        return ""
    return title


def scan_ner(known):
    """返回 {人名: [出场章, ...]}；known 为待侦测人名集合。"""
    names = sorted({n for n in known if n and len(n) >= 2}, key=len, reverse=True)
    hits = {}
    if not names:
        return hits
    pat = re.compile("|".join(re.escape(n) for n in names))
    for book in NER_BOOKS:
        path = BOOKS / book
        if not path.exists():
            continue
        chapter = book.replace(".txt", "")
        for ln in _read_lines(path):
            s = ln.strip().strip("　")
            m = CHAPTER_RE.match(s)
            if m:
                chapter = _clean_chapter(m.group(1) + "年") or chapter
            else:
                m2 = JUAN_RE.match(s)
                if m2:
                    chapter = _clean_chapter(m2.group(1)) or chapter
            for mm in pat.finditer(ln):
                name = mm.group(0)
                bucket = hits.setdefault(name, [])
                if chapter not in bucket:
                    bucket.append(chapter)
    return hits


