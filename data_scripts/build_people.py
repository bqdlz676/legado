def run_check(primary, dup_rows, core, aliases, princes, eras, terms):
    problems = []

    # 1. 人物主表：每条带 source + confidence，枚举合法
    for r in primary:
        if not r["source"]:
            problems.append(f"person 缺 source：{r['name']}")
        if r["confidence"] not in (CONF_HIGH, CONF_MEDIUM, CONF_LOW):
            problems.append(f"person confidence 非法：{r['name']}={r['confidence']}")

    # 2. 核心档案：≥14 列，置信合法
    for c in core.values():
        if c["confidence"] not in (CONF_HIGH, CONF_MEDIUM, CONF_LOW):
            problems.append(f"core confidence 非法：{c['name']}")
        if not c["source"]:
            problems.append(f"core 缺 source：{c['name']}")

    # 3. 别名：别名/归属/类型齐备（国可空，运行时按锚点补）
    for r in aliases:
        if not (r["alias"] and r["owner"] and r["atype"]):
            problems.append(f"alias 字段残缺：{r}")

    # 4. 同名分组：≥2 人
    groups = {}
    for r in dup_rows:
        groups.setdefault(r["name"], []).append(r)
    for name, members in groups.items():
        if len(members) < 2:
            problems.append(f"dup 分组不足 2 人：{name}")

    # 5. 王公：年份不自相矛盾；政权覆盖
    states = {r["state"] for r in princes}
    missing = [s for s in REQUIRED_REGIMES if s not in states]
    for r in princes:
        if r["start"] is not None and r["end"] is not None and r["end"] < r["start"]:
            problems.append(f"王公年份倒挂：{r['state']}{r['title']} {r['start']}>{r['end']}")

    # 6. 年号：a<=b，JSON 合法
    for e in eras:
        if e["b"] < e["a"]:
            problems.append(f"年号年份倒挂：{e['n']}")

    # 7. 词表长度（与写出一致，先去重限长）
    seen, capped = set(), []
    for t in terms:
        if is_cjk_term(t) and t not in seen:
            seen.add(t)
            capped.append(t)
    terms = capped[:30000]
    for t in terms:
        if not is_cjk_term(t):
            problems.append(f"term 长度/字形非法：{t}")
            break

    print("== 构建自检 ==")
    print(f"  person 主表：{len(primary)} 条")
    conf_dist = {}
    for r in primary:
        conf_dist[r["confidence"]] = conf_dist.get(r["confidence"], 0) + 1
    print(f"  person 置信分布：{conf_dist}")
    print(f"  person_dup 分组：{len(groups)} 组 / {len(dup_rows)} 行")
    print(f"  person_core L1：{len(core)} 人")
    print(f"  person_alias：{len(aliases)} 条")
    print(f"  princes：{len(princes)} 条，政权 {len(states)} 个")
    print(f"  era 年号：{len(eras)} 条")
    print(f"  person_terms：{len(terms)} 条")
    if missing:
        print(f"  ⚠ 未覆盖政权：{missing}")
    if problems:
        print("  ✗ 自检未通过：")
        for p in problems[:20]:
            print("   -", p)
        return False
    print("  ✓ 自检通过")
    return True


